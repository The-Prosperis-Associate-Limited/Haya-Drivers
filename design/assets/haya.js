document.querySelectorAll("[data-i]").forEach((el) => {
  const svg = document.createElementNS("http://www.w3.org/2000/svg", "svg");
  svg.setAttribute("viewBox", "0 0 24 24");
  svg.setAttribute("class", "ic " + (el.getAttribute("class") || ""));
  svg.setAttribute("aria-hidden", "true");
  svg.innerHTML = ICONS[el.dataset.i] || "";
  el.replaceWith(svg);
});

const sidebar = document.querySelector(".sidebar");
const scrim = document.querySelector(".scrim");
const setDrawer = (open) => {
  sidebar?.classList.toggle("open", open);
  scrim?.classList.toggle("open", open);
};
document.querySelector(".menu-btn")?.addEventListener("click", () => setDrawer(true));
document.querySelector(".sb-close")?.addEventListener("click", () => setDrawer(false));
scrim?.addEventListener("click", () => setDrawer(false));

document.querySelectorAll(".tabs").forEach((tabs) => {
  tabs.addEventListener("click", (event) => {
    const button = event.target.closest("button");
    if (!button) return;
    tabs.querySelectorAll("button").forEach((b) => b.classList.toggle("on", b === button));
  });
});

document.querySelectorAll(".toggle").forEach((toggle) => {
  toggle.addEventListener("click", () => {
    const on = toggle.getAttribute("aria-pressed") !== "true";
    toggle.setAttribute("aria-pressed", String(on));
    const label = toggle.querySelector("[data-label]");
    if (label) label.textContent = on ? label.dataset.on : label.dataset.off;
  });
});

document.querySelectorAll("[data-respond]").forEach((button) => {
  button.addEventListener("click", () => {
    const offer = button.closest(".offer");
    const yes = button.dataset.respond === "yes";
    offer.querySelector(".offer-actions").outerHTML = yes
      ? '<span class="chip green" style="justify-self:start">✓ You confirmed you\'re available - the team will be in touch</span>'
      : '<span class="chip red" style="justify-self:start">Marked as not available</span>';
  });
});
